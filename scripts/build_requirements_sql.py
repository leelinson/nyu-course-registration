"""Turn data/requirements/*.json into one SQL file that loads them.

Usage: python3 scripts/build_requirements_sql.py > supabase/seed_requirements.sql

Each JSON file describes one program's requirement tree. Re-running the SQL
replaces that program's requirements, so the JSON files stay the source of truth.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "requirements"
RULES = {"all", "choose_n", "credits_min"}


def q(value):
    """Quote a value as a SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def split_code(code):
    subject, number = code.split(" ", 1)
    return subject, number


def course_sql(code, info):
    subject, number = split_code(code)
    credits = info.get("credits")
    title = info.get("title") or code
    return (
        "insert into courses (subject, number, title, credits_min, credits_max) "
        f"values ({q(subject)}, {q(number)}, {q(title)}, {q(credits)}, {q(credits)}) "
        "on conflict (subject, number) do update set "
        "title = case when excluded.title = courses.subject || ' ' || courses.number "
        "then courses.title else excluded.title end, "
        "credits_min = coalesce(excluded.credits_min, courses.credits_min), "
        "credits_max = coalesce(excluded.credits_max, courses.credits_max);"
    )


class GroupWriter:
    def __init__(self, known_courses, path):
        self.known = known_courses
        self.path = path
        self.lines = []
        self.count = 0

    def write(self, group, parent_var, position):
        rule = group["rule"]
        if rule not in RULES:
            sys.exit(f"{self.path.name}: unknown rule {rule!r} in {group['label']!r}")
        if rule == "choose_n" and "n" not in group:
            sys.exit(f"{self.path.name}: {group['label']!r} is choose_n without n")
        if rule == "credits_min" and "credits" not in group:
            sys.exit(f"{self.path.name}: {group['label']!r} is credits_min without credits")
        if not group.get("courses") and not group.get("children"):
            sys.exit(f"{self.path.name}: {group['label']!r} has no courses or children")

        self.count += 1
        var = f"g{self.count}"
        parent = parent_var or "null"
        self.lines.append(
            "  insert into requirement_groups "
            "(program_id, parent_id, position, label, rule_type, n, credits, note) "
            f"values (pid, {parent}, {position}, {q(group['label'])}, {q(rule)}, "
            f"{q(group.get('n'))}, {q(group.get('credits'))}, {q(group.get('note'))}) "
            f"returning id into {var};"
        )

        for member in group.get("courses", []):
            if isinstance(member, dict):
                self.lines.append(
                    "  insert into requirement_courses (group_id, subject_pattern) "
                    f"values ({var}, {q(member['pattern'])});"
                )
            else:
                if member not in self.known:
                    sys.exit(f"{self.path.name}: {member} is used but missing from \"courses\"")
                subject, number = split_code(member)
                self.lines.append(
                    "  insert into requirement_courses (group_id, course_id) "
                    f"select {var}, id from courses where subject = {q(subject)} and number = {q(number)};"
                )

        for i, child in enumerate(group.get("children", [])):
            self.write(child, var, i)


def program_sql(path):
    spec = json.loads(path.read_text())
    prog = spec["program"]
    out = [f"-- {path.name}"]
    out += [course_sql(code, info) for code, info in sorted(spec["courses"].items())]

    writer = GroupWriter(spec["courses"], path)
    for i, group in enumerate(spec["groups"]):
        writer.write(group, None, i)

    match = (
        f"slug = {q(prog['slug'])} and catalog_year = {q(prog['catalog_year'])} "
        f"and concentration is not distinct from {q(prog.get('concentration'))}"
    )
    variables = " ".join(f"g{i} int;" for i in range(1, writer.count + 1))
    out += [
        "do $$",
        f"declare pid int; {variables}",
        "begin",
        f"  select id into strict pid from programs where {match};",
        "  delete from requirement_groups where program_id = pid;",
        "  update programs set requirements_reviewed = false where id = pid;",
        *writer.lines,
        "end $$;",
        "",
    ]
    return "\n".join(out)


def main():
    files = sorted(DATA.glob("*.json"))
    print("-- Generated by scripts/build_requirements_sql.py. Edit the JSON, not this file.\n")
    print("begin;\n")
    for path in files:
        print(program_sql(path))
    print("commit;")


if __name__ == "__main__":
    main()
